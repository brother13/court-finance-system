-- 法院专项账务系统：长耗时财务操作异步任务基础表
-- 适用：MySQL 8.0；仅新增表，不修改现有业务数据，可重复执行。
--
-- 财务约束：
-- 1. fin_async_job 只记录任务控制状态，不替代正式业务表和 sys_audit_log。
-- 2. fin_async_job_item 冻结本次处理的业务源记录；同一任务内同一业务源只能出现一次。
-- 3. fin_case_fund_import_stage 是导入暂存区，整批校验完成前不得写入正式业务表。
-- 4. 凭证生成仍须以一张完整凭证为最小事务单元，凭证及业务源回写成功后再更新任务明细。
-- 5. 应用层任务状态固定为 QUEUED、RUNNING、SUCCEEDED、PARTIAL_FAILED、FAILED。

create table if not exists fin_async_job (
    job_id varchar(36) primary key,
    account_set_id varchar(36) not null,
    fiscal_year int not null,
    period varchar(7) not null,
    job_type varchar(50) not null,
    client_request_id varchar(64) not null,
    status varchar(20) not null default 'QUEUED',
    stage varchar(30) not null default 'QUEUED',
    payload_json longtext,
    result_json longtext,
    source_file_name varchar(255),
    source_file_path varchar(1000),
    source_file_hash char(64),
    total_count int not null default 0,
    processed_count int not null default 0,
    success_count int not null default 0,
    failure_count int not null default 0,
    progress_percent decimal(5,2) not null default 0,
    message varchar(500),
    error_message varchar(2000),
    worker_token varchar(100),
    attempt_count int not null default 0,
    queued_time datetime not null,
    started_time datetime,
    heartbeat_time datetime,
    finished_time datetime,
    created_by varchar(36),
    created_time datetime,
    updated_by varchar(36),
    updated_time datetime,
    del_flag int not null default 0,
    version int not null default 0,
    remark varchar(500),
    unique key uk_async_job_request (account_set_id, job_type, client_request_id),
    key idx_async_job_queue (status, del_flag, queued_time, job_id),
    key idx_async_job_account_list (account_set_id, fiscal_year, period, job_type, status, del_flag, created_time),
    key idx_async_job_heartbeat (status, del_flag, heartbeat_time),
    key idx_async_job_file_hash (account_set_id, job_type, source_file_hash)
);

create table if not exists fin_async_job_item (
    item_id varchar(36) primary key,
    job_id varchar(36) not null,
    account_set_id varchar(36) not null,
    fiscal_year int not null,
    period varchar(7) not null,
    item_no int not null,
    source_row_no int,
    source_type varchar(50) not null,
    source_id varchar(36) not null,
    group_key varchar(255),
    amount decimal(18,2) not null default 0,
    status varchar(20) not null default 'QUEUED',
    result_json longtext,
    error_code varchar(100),
    error_message varchar(2000),
    voucher_id varchar(36),
    voucher_no int,
    voucher_period varchar(7),
    started_time datetime,
    finished_time datetime,
    created_by varchar(36),
    created_time datetime,
    updated_by varchar(36),
    updated_time datetime,
    del_flag int not null default 0,
    version int not null default 0,
    remark varchar(500),
    unique key uk_async_job_item_source (job_id, source_type, source_id),
    key idx_async_job_item_queue (job_id, status, del_flag, item_no, item_id),
    key idx_async_job_item_error (job_id, status, del_flag, error_code, item_no),
    key idx_async_job_item_source (account_set_id, source_type, source_id, del_flag),
    key idx_async_job_item_voucher (account_set_id, voucher_id, del_flag)
);

create table if not exists fin_case_fund_import_stage (
    stage_id varchar(36) primary key,
    job_id varchar(36) not null,
    account_set_id varchar(36) not null,
    fiscal_year int not null,
    period varchar(7) not null,
    source_row_no int not null,
    source_fingerprint varchar(64) not null default '',
    raw_json longtext,
    normalized_json longtext,
    validation_status varchar(20) not null default 'PENDING',
    validation_errors_json longtext,
    persistence_status varchar(20) not null default 'PENDING',
    target_type varchar(50),
    target_id varchar(36),
    error_code varchar(100),
    error_message varchar(2000),
    created_by varchar(36),
    created_time datetime,
    updated_by varchar(36),
    updated_time datetime,
    del_flag int not null default 0,
    version int not null default 0,
    remark varchar(500),
    unique key uk_case_fund_import_stage_row (job_id, source_row_no),
    key idx_case_fund_import_stage_work (job_id, validation_status, persistence_status, del_flag, source_row_no),
    key idx_case_fund_import_stage_fingerprint (job_id, source_fingerprint, del_flag),
    key idx_case_fund_import_stage_target (account_set_id, target_type, target_id, del_flag)
);
