}

$book = file_get_contents(__DIR__ . '/../app/finance/model/Book.php');
$rbac = file_get_contents(__DIR__ . '/../database/migration_rbac.sql');

$checks = [
    [$book, "case 'subjectSummary'", 'Book should route subjectSummary'],
    [$book, "case 'subjectSummaryPdf'", 'Book should route subjectSummaryPdf'],
    [$book, 'public function subjectSummary', 'Book should expose subjectSummary'],
    [$book, 'public function subjectSummaryPdf', 'Book should expose subjectSummaryPdf'],
    [$book, 'new \Mpdf\Mpdf', 'Subject summary PDF should be generated by backend mPDF'],
    [$book, "'Content-Type' => 'application/pdf'", 'Subject summary PDF should return application/pdf'],
    [$book, "'Content-Disposition' => 'inline;", 'Subject summary PDF should open inline in the browser'],
    [$book, '暂无科目汇总数据', 'Subject summary PDF should render an explicit empty row instead of blank pages'],
    [$book, 'sortSubjectSummaryRows($rows)', 'Subject summary rows should be sorted before both page and PDF rendering'],
    [$book, 'appendSubjectSummaryTree', 'Subject summary sorting should keep child subjects below their parent'],
    [$book, 'subjectTypeOrder', 'Subject summary sorting should keep the financial subject type order'],
    [$book, "requirePermission('book:view')", 'Subject summary should require book view permission'],
    [$book, 'ancestorSubjectCodes($detail[\'subject_code\']', 'Subject summary should aggregate details to every configured subject level'],
    [$book, 'subject_type', 'Subject summary rows should expose subject type for financial statement ordering'],
    [$book, "'start_period'", 'Subject summary should accept a start accounting period'],
    [$book, "'end_period'", 'Subject summary should accept an end accounting period'],
    [$book, "where('d.period', 'between'", 'Subject summary should query voucher details by accounting period range'],
    [$book, 'subjectRangeUpperBound', 'Subject summary should include descendants of the ending subject code'],
    [$book, 'subjectRangeUpperBound($subjectCode', 'Detail ledger should include descendants when drilling into a non-leaf subject'],
    [$book, "'v.void_flag' => 0", 'Subject summary should include every non-voided voucher regardless of audit or posting status'],
    [$book, "'entry_count'", 'Subject summary rows should expose entry count'],
    [$rbac, "'menu:book:subject_summary'", 'RBAC should define subject summary menu permission'],
    [$rbac, "'科目汇总表'", 'RBAC should name the subject summary menu'],
];

foreach ($checks as [$haystack, $needle, $message]) {
    if (strpos($haystack, $needle) === false) {
        fwrite(STDERR, $message . PHP_EOL);
        exit(1);
    }
}

if (strpos($book, 'table { width: 100%; border-collapse: collapse; table-layout: fixed; page-break-inside: avoid; }') !== false) {
    fwrite(STDERR, 'Subject summary PDF should not force an oversized table to stay on one page in mPDF' . PHP_EOL);
    exit(1);
}

if (strpos($book, '<tfoot>') !== false) {
    fwrite(STDERR, 'Subject summary PDF should not use tfoot because mPDF can repeat it into blank pages' . PHP_EOL);
    exit(1);
}

foreach (['table-header-group', 'page-break-inside', 'autosize="1"', 'line-height: \' . $rowHeightMm'] as $unsafePdfStyle) {
    if (strpos($book, $unsafePdfStyle) !== false) {
        fwrite(STDERR, 'Subject summary PDF should avoid mPDF pagination-sensitive table CSS: ' . $unsafePdfStyle . PHP_EOL);
        exit(1);
    }
}

require_once __DIR__ . '/../app/finance/model/Common.php';
require_once __DIR__ . '/../app/finance/model/Book.php';

$model = new app\finance\model\Book();
$summaryCode = new ReflectionMethod(app\finance\model\Book::class, 'subjectSummaryCode');
$summaryCode->setAccessible(true);
$ancestors = new ReflectionMethod(app\finance\model\Book::class, 'ancestorSubjectCodes');
$ancestors->setAccessible(true);
$upperBound = new ReflectionMethod(app\finance\model\Book::class, 'subjectRangeUpperBound');
$upperBound->setAccessible(true);
$sortRows = new ReflectionMethod(app\finance\model\Book::class, 'sortSubjectSummaryRows');
$sortRows->setAccessible(true);
$rule = [4, 2, 2, 2];
$subjectMap = [
    '1002' => ['subject_code' => '1002'],
    '100201' => ['subject_code' => '100201'],
    '10020101' => ['subject_code' => '10020101'],
];

if ($ancestors->invoke($model, '10020101', $subjectMap, $rule) !== ['1002', '100201', '10020101']) {
    fwrite(STDERR, 'Subject summary should expose every configured level for a detail subject' . PHP_EOL);
    exit(1);
}

if ($summaryCode->invoke($model, '10020101', 1, $rule) !== '1002') {
    fwrite(STDERR, 'Subject summary should roll detail code 10020101 up to level 1 code 1002' . PHP_EOL);
    exit(1);
}

if ($summaryCode->invoke($model, '10020101', 2, $rule) !== '100201') {
    fwrite(STDERR, 'Subject summary should roll detail code 10020101 up to level 2 code 100201' . PHP_EOL);
    exit(1);
}

if ($upperBound->invoke($model, '1002', 10) !== '1002999999') {
    fwrite(STDERR, 'Subject range upper bound should include descendants of ending subject code' . PHP_EOL);
    exit(1);
}

$sorted = $sortRows->invoke($model, [
    ['subject_code' => '660101', 'subject_type' => 'PROFIT_LOSS', 'level_no' => 2],
    ['subject_code' => '100201', 'subject_type' => 'ASSET', 'level_no' => 2],
    ['subject_code' => '2202', 'subject_type' => 'LIABILITY', 'level_no' => 1],
    ['subject_code' => '6601', 'subject_type' => 'PROFIT_LOSS', 'level_no' => 1],
    ['subject_code' => '1002', 'subject_type' => 'ASSET', 'level_no' => 1],
    ['subject_code' => '1001', 'subject_type' => 'ASSET', 'level_no' => 1],
]);
$sortedCodes = array_column($sorted, 'subject_code');
if ($sortedCodes !== ['1001', '1002', '100201', '2202', '6601', '660101']) {
    fwrite(STDERR, 'Subject summary PDF should use the same subject type and tree order as the page: ' . implode(',', $sortedCodes) . PHP_EOL);
    exit(1);
}

echo 'Book subject summary test passed' . PHP_EOL;
