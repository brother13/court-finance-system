$book = file_get_contents(__DIR__ . '/../app/finance/model/Book.php');

$checks = [
    [$book, "case 'subjectBalancePdf'", 'Book should route subjectBalancePdf'],
    [$book, 'public function subjectBalancePdf', 'Book should expose subjectBalancePdf'],
    [$book, 'buildSubjectBalancePdfHtml', 'Subject balance PDF should have a dedicated HTML template'],
    [$book, 'subjectBalanceDisplayRows', 'Subject balance PDF should render grouped subtotal rows like the page'],
    [$book, 'new \Mpdf\Mpdf', 'Subject balance PDF should be generated by backend mPDF'],
    [$book, "'Content-Type' => 'application/pdf'", 'Subject balance PDF should return application/pdf'],
    [$book, "'Content-Disposition' => 'inline;", 'Subject balance PDF should open inline in the browser'],
    [$book, '暂无科目余额数据', 'Subject balance PDF should render an explicit empty row instead of blank pages'],
    [$book, '期初借方', 'Subject balance PDF should include opening debit column'],
    [$book, '本期借方', 'Subject balance PDF should include current debit column'],
    [$book, '累计借方', 'Subject balance PDF should include year debit column'],
    [$book, '期末借方', 'Subject balance PDF should include ending debit column'],
];

foreach ($checks as [$haystack, $needle, $message]) {
    if (strpos($haystack, $needle) === false) {
        fwrite(STDERR, $message . PHP_EOL);
        exit(1);
    }
}

foreach (['table-header-group', 'page-break-inside', 'autosize="1"', '<tfoot>'] as $unsafePdfStyle) {
    if (strpos($book, $unsafePdfStyle) !== false) {
        fwrite(STDERR, 'Subject balance PDF should avoid mPDF pagination-sensitive table CSS: ' . $unsafePdfStyle . PHP_EOL);
        exit(1);
    }
}

