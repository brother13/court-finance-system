$book = file_get_contents(__DIR__ . '/../app/finance/model/Book.php');

$checks = [
    [$book, "case 'detailLedgerPdf'", 'Book should route detailLedgerPdf'],
    [$book, 'public function detailLedgerPdf', 'Book should expose detailLedgerPdf'],
    [$book, 'loadDetailLedgerRowsForPdf', 'Detail ledger PDF should load all filtered rows instead of the current screen page'],
    [$book, 'buildDetailLedgerPdfHtml', 'Detail ledger PDF should have a dedicated HTML template'],
    [$book, 'formatDetailLedgerAuxDesc', 'Detail ledger PDF should format auxiliary descriptions like the page'],
    [$book, 'new \Mpdf\Mpdf', 'Detail ledger PDF should be generated by backend mPDF'],
    [$book, "'Content-Type' => 'application/pdf'", 'Detail ledger PDF should return application/pdf'],
    [$book, "'Content-Disposition' => 'inline;", 'Detail ledger PDF should open inline in the browser'],
    [$book, '暂无明细账数据', 'Detail ledger PDF should render an explicit empty row instead of blank pages'],
    [$book, 'voucher_date asc,v.voucher_no asc,d.line_no asc', 'Detail ledger PDF should preserve ledger chronological voucher ordering'],
    [$book, "'pagesize' => 200", 'Detail ledger PDF should page through full filtered data using the backend page cap'],
];

foreach ($checks as [$haystack, $needle, $message]) {
    if (strpos($haystack, $needle) === false) {
        fwrite(STDERR, $message . PHP_EOL);
        exit(1);
    }
}

foreach (['table-header-group', 'page-break-inside', 'autosize="1"', '<tfoot>'] as $unsafePdfStyle) {
    if (strpos($book, $unsafePdfStyle) !== false) {
        fwrite(STDERR, 'Detail ledger PDF should avoid mPDF pagination-sensitive table CSS: ' . $unsafePdfStyle . PHP_EOL);
        exit(1);
    }
}

require_once __DIR__ . '/../app/finance/model/Common.php';
require_once __DIR__ . '/../app/finance/model/Book.php';

$model = new app\finance\model\Book();
$formatAuxDesc = new ReflectionMethod(app\finance\model\Book::class, 'formatDetailLedgerAuxDesc');
$formatAuxDesc->setAccessible(true);

$formatted = $formatAuxDesc->invoke($model, 'case_no:(2026)辽0111执1号; receipt_no:SP001 / party_name:张三');
if ($formatted !== '(2026)辽0111执1号；SP001；张三') {
    fwrite(STDERR, 'Detail ledger PDF should strip auxiliary type prefixes: ' . $formatted . PHP_EOL);
    exit(1);
}

echo 'Book detail ledger PDF test passed' . PHP_EOL;
