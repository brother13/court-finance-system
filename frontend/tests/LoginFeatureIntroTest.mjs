import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import assert from 'assert'

const __dirname = dirname(fileURLToPath(import.meta.url))
const login = readFileSync(resolve(__dirname, '../src/views/auth/LoginView.vue'), 'utf8')
const styles = readFileSync(resolve(__dirname, '../src/styles/app.css'), 'utf8')

assert(login.includes('class="login-card"'), 'login page should use a single centered SaaS login card')
assert(login.includes('raspberryLogo'), 'login page should keep the raspberry brand logo')
assert(login.includes('class="login-shell"'), 'login page should group identity and card in one centered shell')
assert(login.includes('class="login-identity"'), 'login logo and product name should sit above the card')
assert(login.includes('class="login-brand-row"'), 'login identity should keep logo and product name in a dedicated brand row')
assert(login.includes('class="login-identity-subtitle"'), 'login subtitle should be separated from the brand row')
assert(login.includes('login-logo-frame'), 'login card should present the logo in a refined frame')
assert(login.includes('<strong>树莓法衡</strong>'), 'login identity should use the short product name')
assert(!login.includes('<strong>树莓法衡专项账务系统</strong>'), 'login identity should not use the long product name')
assert(!login.includes('login-card-accent'), 'login card should not keep the top brand strip')
assert(!login.includes('login-card-footer'), 'login card should not keep an in-card footer')
assert(login.includes('<h1>账户登录</h1>'), 'login card header should only keep the account login title')
assert(!login.includes('<h1>欢迎登录</h1>'), 'login card should not show a second welcome heading')
assert(!login.includes('请选择单位，使用系统账号进入账务工作台。'), 'login card should not show extra helper copy above the form')
assert(login.includes('用户单位') && login.includes('用户名') && login.includes('密码'), 'login card should keep the required login fields')
assert(login.includes('class="login-page-footer"'), 'login page should render a page-level copyright footer')
assert(login.includes('Copyright © 2026 树莓（沈阳）软件科技发展有限公司 技术支持'), 'login page should show the requested copyright support text')
assert(!login.includes('login-brand-panel'), 'login page should not render the left introduction panel')
assert(!login.includes('login-status-grid'), 'login page should not render feature introduction cards')
assert(!login.includes('一张网') && !login.includes('案号+单据号') && !login.includes('按收费方式制证'), 'login page should not include business feature marketing copy')
assert(styles.includes('justify-content: center'), 'login page should center the login card')
assert(styles.includes('linear-gradient(135deg, rgba(30, 90, 168, 0.1)'), 'login page should use a subtle blue-gray gradient background')
assert(styles.includes('.login-page::before'), 'login page should include restrained geometric background lines')
assert(styles.includes('.login-page::after'), 'login page should include a faint institutional silhouette')
assert(!styles.includes("url('../assets/login-bg.jpg')"), 'login page should not use the generated background image')
assert(styles.includes('width: min(420px, 100%)'), 'login shell should have a compact SaaS width')
assert(styles.includes('.login-identity {'), 'login page should style an external identity block')
assert(styles.includes('.login-brand-row {'), 'login page should style a separated brand row')
assert(styles.includes('.login-identity-subtitle {'), 'login page should style a separated subtitle')
assert(!styles.includes('.login-identity-subtitle::before'), 'login subtitle should not use side divider lines')
assert(!styles.includes('.login-identity-subtitle::after'), 'login subtitle should not use side divider lines')
assert(styles.includes('.login-page-footer {'), 'login page should style the page-level footer')
assert(!styles.includes('grid-template-columns: minmax(560px, 1.24fr) minmax(340px, 0.76fr)'), 'login page should not keep the old two-column layout')
assert(!styles.includes('.login-status-grid'), 'login CSS should not keep feature card styles')

console.log('Login SaaS layout test passed')
