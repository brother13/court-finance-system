import { readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import assert from 'assert'

const __dirname = dirname(fileURLToPath(import.meta.url))
const app = readFileSync(resolve(__dirname, '../src/App.vue'), 'utf8')
const router = readFileSync(resolve(__dirname, '../src/router/index.ts'), 'utf8')
const api = readFileSync(resolve(__dirname, '../src/api/books.ts'), 'utf8')
const types = readFileSync(resolve(__dirname, '../src/types/api.ts'), 'utf8')
const viewPath = resolve(__dirname, '../src/views/books/SubjectSummaryView.vue')

assert(existsSync(viewPath), 'subject summary view should exist')
const view = readFileSync(viewPath, 'utf8')

assert(app.includes('menu:book:subject_summary'), 'sidebar should check subject summary menu permission')
assert(app.includes('index="/books/subject-summary"'), 'sidebar should route to subject summary page')
assert(app.includes('科目汇总表'), 'sidebar and title map should show subject summary menu item')

assert(router.includes("const SubjectSummaryView = () => import('../views/books/SubjectSummaryView.vue')"), 'router should lazy-load subject summary view')
assert(router.includes("'/books/subject-summary'"), 'router should register subject summary route')
assert(router.includes("permission: 'menu:book:subject_summary'"), 'subject summary route should require menu permission')

assert(api.includes("apiAction('/book/subjectSummary'"), 'books API should expose subject summary endpoint')
assert(api.includes("apiBlobAction('/book/subjectSummaryPdf'"), 'books API should expose backend subject summary PDF endpoint')
assert(api.includes('start_period'), 'books API should send start period for subject summary')
assert(api.includes('end_period'), 'books API should send end period for subject summary')
assert(types.includes('SubjectSummaryRow'), 'API types should include subject summary rows')

assert(view.includes('subjectStartCode'), 'view should filter by starting subject code')
assert(view.includes('subjectEndCode'), 'view should filter by ending subject code')
assert(view.includes('会计期间'), 'subject summary should use accounting period range filters')
assert(!view.includes('会计日期'), 'subject summary should not use natural date range filters')
assert(!view.includes('dateRange'), 'subject summary should not keep date range state for query filters')
assert(!view.includes('el-date-picker'), 'subject summary should use period selects like subject balance')
assert(view.includes('startPeriod'), 'subject summary should track start accounting period')
assert(view.includes('endPeriod'), 'subject summary should track end accounting period')
assert(view.includes('periodOptions'), 'subject summary should expose period options like subject balance')
assert(view.includes('periodLabel'), 'subject summary should format period labels like subject balance')
assert(!view.includes('subjectLevel'), 'subject summary should show every subject level instead of filtering to one summary level')
assert(view.includes('el-popover'), 'subject summary filters should open from a dropdown popover above the table')
assert(view.includes('summary-filter-button'), 'subject summary should use a compact filter dropdown button')
assert(view.includes('summary-filter-popover'), 'subject summary should render filter controls in the dropdown panel')
assert(view.includes('summaryFilterText'), 'subject summary filter button should summarize the selected period range')
assert(view.includes('collapsedSubjectCodes'), 'subject summary should track collapsed parent subjects')
assert(view.includes('toggleSubjectCollapse'), 'subject summary should allow parent subjects to expand or collapse children')
assert(view.includes('visibleRows'), 'subject summary should hide descendants of collapsed subjects')
assert(view.includes('orderedRows'), 'subject summary should render rows in a stable financial subject order')
assert(view.includes('subjectTypeOrder'), 'subject summary should sort subject types by accounting category')
assert(view.includes('parentCodeFor'), 'subject summary should resolve each subject row to its nearest parent code')
assert(view.includes('appendSubjectTree'), 'subject summary should append child subjects directly below their parent')
assert(view.includes('compareSubjectRows'), 'subject summary should sort top-level subjects by type and siblings by code')
assert(types.includes('subject_type'), 'subject summary row type should include subject type')
assert(view.includes('hasChildSubject'), 'subject summary should show expand controls only for subjects with children')
assert(view.includes('leaf_flag'), 'subject summary should receive leaf flags so totals avoid double-counting parent and child rows')
assert(!view.includes('search-filter-section'), 'subject summary should not use the old full-width inline filter strip')
assert(view.includes('debit_amount'), 'view should show debit amount')
assert(view.includes('credit_amount'), 'view should show credit amount')
assert(!view.includes('prop="level_no" label="级次"'), 'subject summary table should not show subject level column')
assert(!view.includes('prop="entry_count" label="分录数"'), 'subject summary table should not show voucher entry count column')
assert(!view.includes('prop="balance_amount" label="借贷净额"'), 'subject summary table should not show net amount column')
assert(view.includes('label="金额合计借方"'), 'subject summary table should show total debit amount column')
assert(view.includes('label="金额合计贷方"'), 'subject summary table should show total credit amount column')
assert(view.includes("headers = ['科目编码', '科目名称', '金额合计借方', '金额合计贷方']"), 'subject summary export should keep the same four visible columns')
assert(view.includes("v-permission=\"'book:export'\""), 'export button should require book export permission')
assert(!view.includes("import * as XLSX from 'xlsx'"), 'view should not eagerly import xlsx for Excel export')
assert(view.includes("await import('xlsx')"), 'view should dynamically import xlsx only when exporting')
assert(view.includes('XLSX.writeFile'), 'view should write subject summary Excel file')
assert(view.includes('printReport'), 'subject summary should provide browser print action')
assert(!view.includes('createReportPrintPdf'), 'subject summary print should not generate image-based PDF in the browser')
assert(view.includes('booksApi.subjectSummaryPdf'), 'subject summary print should call backend PDF endpoint')
assert(view.includes('URL.createObjectURL'), 'subject summary print should open a generated PDF blob')
assert(view.includes('window.open'), 'subject summary print should preview PDF in browser')
assert(view.includes(':loading="printing"'), 'subject summary print button should show a loading state while backend PDF is generated')
assert(view.includes('if (printing.value) return'), 'subject summary should prevent duplicate print clicks while loading')
assert(view.includes('printing.value = false'), 'subject summary should clear print loading state after PDF generation')
assert(!view.includes('科目汇总表 · {{ context.period }}'), 'subject summary header should not repeat accounting period')
assert(view.includes('@row-dblclick="openDetailLedger"'), 'summary row double click should drill down to detail ledger')
assert(view.includes('@row-contextmenu="openDetailLedgerMenu"'), 'summary row context menu should drill down to detail ledger')
assert(view.includes("path: '/books/detail-ledger'"), 'summary drilldown should route to detail ledger')
assert(view.includes('subject_code: row.subject_code'), 'summary drilldown should pass subject code')
assert(view.includes('period: filters.endPeriod'), 'summary drilldown should pass selected ending period')
assert(view.includes('year: context.year'), 'summary drilldown should pass year')

console.log('Book subject summary frontend test passed')
