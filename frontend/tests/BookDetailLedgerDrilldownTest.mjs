import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import assert from 'assert'

const __dirname = dirname(fileURLToPath(import.meta.url))
const view = readFileSync(resolve(__dirname, '../src/views/books/DetailLedgerView.vue'), 'utf8')
const bookModel = readFileSync(resolve(__dirname, '../../backend/app/finance/model/Book.php'), 'utf8')

assert(bookModel.includes('v.voucher_id'), 'detail ledger API should return voucher_id for voucher drilldown')
assert(view.includes('useRoute') && view.includes('useRouter'), 'detail ledger should use route and router')
assert(view.includes('route.query.subject_code'), 'detail ledger should initialize subject from route query')
assert(view.includes('route.query.period'), 'detail ledger should initialize period from route query')
assert(view.includes('route.query.start_period'), 'detail ledger should initialize start period from route query')
assert(view.includes('route.query.end_period'), 'detail ledger should initialize end period from route query')
assert(view.includes('periodMonthRange'), 'detail ledger date range should default to the selected accounting period')
assert(!view.includes('now.getMonth() + 1'), 'detail ledger date range should not use the current natural month')
assert(view.includes('会计期间'), 'detail ledger should query by accounting period')
assert(view.includes('v-model="filters.startPeriod"'), 'detail ledger start period selector should update the queried accounting period range')
assert(view.includes('v-model="filters.endPeriod"'), 'detail ledger end period selector should update the queried accounting period range')
assert(view.includes('startPeriod: filters.startPeriod'), 'detail ledger API should send start period')
assert(view.includes('endPeriod: filters.endPeriod'), 'detail ledger API should send end period')
assert(view.includes('periodOptions'), 'detail ledger should provide accounting period options')
assert(bookModel.includes("'start_period'"), 'detail ledger API should accept start accounting period')
assert(bookModel.includes("'end_period'"), 'detail ledger API should accept end accounting period')
assert(bookModel.includes("where('d.period', 'between'"), 'detail ledger should query voucher details by accounting period range')
assert(view.includes('baseApi.subjects'), 'detail ledger should load subject options for the left subject tree')
assert(view.includes("defaultSubjectCode = '1002'"), 'detail ledger should default to bank deposit subject 1002')
assert(view.includes('ledger-subject-tree'), 'detail ledger should render a left subject selector')
assert(view.includes('@node-click="handleSubjectSelect"'), 'detail ledger subject tree should reload data when a subject is selected')
assert(view.includes(':current-node-key="query.subjectCode"'), 'detail ledger subject tree should highlight the selected subject')
assert(view.includes('query.subjectCode = code'), 'detail ledger should update the queried subject when the tree selection changes')
assert(!view.includes('type="daterange"'), 'detail ledger should not use one coupled date range picker')
assert(!view.includes('type="date"'), 'detail ledger should not use natural date pickers when querying by accounting period')
assert(view.includes('@row-dblclick="openVoucherDetail"'), 'detail ledger row double click should open voucher detail')
assert(view.includes("router.push({ path: `/vouchers/detail/${row.period}/${row.voucher_id}`"), 'detail ledger should route to voucher detail with period and voucher id')
assert(view.includes('filters.endPeriod'), 'detail ledger should query by selected ending period instead of only context period')
assert(view.includes('明细账记录'), 'detail ledger header should keep a clean title')
assert(!view.includes('明细账记录 · {{ selectedPeriod }}'), 'detail ledger header should not repeat accounting period')
assert(view.includes('formatAuxDesc(row.aux_desc)'), 'detail ledger should format auxiliary text before display')
assert(view.includes("part.slice(index + 1)"), 'detail ledger auxiliary display should strip technical type prefixes')
assert(!view.includes('<span v-if="row.aux_desc">{{ row.aux_desc }}</span>'), 'detail ledger should not render raw auxiliary descriptions')

console.log('Book detail ledger drilldown test passed')
